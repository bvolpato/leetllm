CREATE TABLE public.user_personalization_profiles (
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
  tone_preset TEXT DEFAULT 'clear' NOT NULL
    CHECK (tone_preset IN ('clear', 'friendly', 'professional', 'cowboy')),
  explanation_level TEXT DEFAULT 'balanced' NOT NULL
    CHECK (explanation_level IN ('eli5', 'beginner', 'balanced', 'advanced')),
  custom_instructions TEXT DEFAULT '' NOT NULL
    CHECK (char_length(custom_instructions) <= 2000),
  learner_context TEXT DEFAULT '' NOT NULL
    CHECK (char_length(learner_context) <= 4000),
  resume_context TEXT DEFAULT '' NOT NULL
    CHECK (char_length(resume_context) <= 6000),
  resume_filename TEXT CHECK (resume_filename IS NULL OR char_length(resume_filename) BETWEEN 1 AND 255),
  resume_updated_at TIMESTAMPTZ,
  revision INTEGER DEFAULT 1 NOT NULL CHECK (revision > 0),
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

CREATE TABLE public.user_personalized_lessons (
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  article_slug TEXT NOT NULL CHECK (char_length(article_slug) BETWEEN 1 AND 200),
  profile_revision INTEGER NOT NULL CHECK (profile_revision > 0),
  source_hash TEXT NOT NULL CHECK (char_length(source_hash) = 64),
  model_id TEXT NOT NULL CHECK (char_length(model_id) BETWEEN 1 AND 100),
  prompt_version TEXT NOT NULL CHECK (char_length(prompt_version) BETWEEN 1 AND 50),
  markdown TEXT NOT NULL CHECK (char_length(markdown) BETWEEN 1 AND 300000),
  generated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
  PRIMARY KEY (user_id, article_slug)
);

CREATE TABLE public.personalization_generation_usage (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  article_slug TEXT CHECK (article_slug IS NULL OR char_length(article_slug) BETWEEN 1 AND 200),
  request_kind TEXT NOT NULL CHECK (request_kind IN ('lesson', 'resume')),
  status TEXT NOT NULL CHECK (status IN ('claimed', 'succeeded', 'failed')),
  model_id TEXT NOT NULL CHECK (char_length(model_id) BETWEEN 1 AND 100),
  duration_ms INTEGER CHECK (duration_ms IS NULL OR duration_ms >= 0),
  input_chars INTEGER CHECK (input_chars IS NULL OR input_chars >= 0),
  output_chars INTEGER CHECK (output_chars IS NULL OR output_chars >= 0),
  error_code TEXT CHECK (error_code IS NULL OR char_length(error_code) <= 100),
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

CREATE INDEX idx_personalization_generation_usage_user_time
  ON public.personalization_generation_usage(user_id, created_at DESC);

