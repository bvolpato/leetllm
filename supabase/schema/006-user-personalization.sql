CREATE OR REPLACE FUNCTION public.claim_personalization_quota(
  p_article_slug TEXT,
  p_request_kind TEXT,
  p_model_id TEXT,
  p_hourly_limit INTEGER DEFAULT 6
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  current_user_id UUID := auth.uid();
  recent_requests INTEGER;
  claim_id BIGINT;
BEGIN
  IF current_user_id IS NULL THEN
    RAISE EXCEPTION 'Not authenticated' USING ERRCODE = '42501';
  END IF;
  IF p_request_kind IS NULL
    OR p_request_kind NOT IN ('lesson', 'resume')
    OR p_model_id IS NULL
    OR char_length(p_model_id) NOT BETWEEN 1 AND 100
    OR p_hourly_limit IS NULL
    OR p_hourly_limit NOT BETWEEN 1 AND 100
    OR (p_article_slug IS NOT NULL AND char_length(p_article_slug) NOT BETWEEN 1 AND 200)
  THEN
    RAISE EXCEPTION 'Invalid personalization quota request' USING ERRCODE = '22023';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended(current_user_id::TEXT, 0));

  SELECT COUNT(*)
  INTO recent_requests
  FROM public.personalization_generation_usage
  WHERE user_id = current_user_id
    AND created_at >= NOW() - INTERVAL '1 hour';

  IF recent_requests >= p_hourly_limit THEN
    RETURN NULL;
  END IF;

  INSERT INTO public.personalization_generation_usage (
    user_id,
    article_slug,
    request_kind,
    status,
    model_id
  ) VALUES (
    current_user_id,
    p_article_slug,
    p_request_kind,
    'claimed',
    p_model_id
  )
  RETURNING id INTO claim_id;

  RETURN claim_id;
END;
$$;

REVOKE ALL ON FUNCTION public.claim_personalization_quota(TEXT, TEXT, TEXT, INTEGER)
  FROM PUBLIC, anon, service_role;
GRANT EXECUTE ON FUNCTION public.claim_personalization_quota(TEXT, TEXT, TEXT, INTEGER) TO authenticated;

CREATE OR REPLACE FUNCTION public.update_personalization_profile_revision()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.tone_preset IS DISTINCT FROM OLD.tone_preset
    OR NEW.explanation_level IS DISTINCT FROM OLD.explanation_level
    OR NEW.custom_instructions IS DISTINCT FROM OLD.custom_instructions
    OR NEW.learner_context IS DISTINCT FROM OLD.learner_context
    OR NEW.resume_context IS DISTINCT FROM OLD.resume_context
    OR NEW.resume_filename IS DISTINCT FROM OLD.resume_filename
    OR NEW.resume_updated_at IS DISTINCT FROM OLD.resume_updated_at
  THEN
    NEW.revision = OLD.revision + 1;
    NEW.updated_at = NOW();
  ELSE
    NEW.revision = OLD.revision;
    NEW.updated_at = OLD.updated_at;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER update_user_personalization_profile_revision
  BEFORE UPDATE ON public.user_personalization_profiles
  FOR EACH ROW EXECUTE FUNCTION public.update_personalization_profile_revision();

CREATE TRIGGER update_user_personalized_lessons_updated_at
