/**
 * Fetches Google's published Googlebot IP ranges and writes them to
 * src/lib/googlebot-cidrs.json. Run this before `next build`.
 *
 * Google publishes two separate lists:
 *  - Googlebot special crawlers: https://developers.google.com/search/apis/ipranges/googlebot.json
 *  - Google's user-triggered fetchers: https://developers.google.com/search/apis/ipranges/user-triggered-fetchers.json
 *
 * We merge both so we catch all verified Google crawler IPs.
 */

import { writeFileSync, mkdirSync } from 'fs'
import { join } from 'path'

const GOOGLEBOT_URL =
    'https://developers.google.com/search/apis/ipranges/googlebot.json'
const USER_TRIGGERED_URL =
    'https://developers.google.com/search/apis/ipranges/user-triggered-fetchers.json'
const SPECIAL_CRAWLERS_URL =
    'https://developers.google.com/search/apis/ipranges/special-crawlers.json'

interface IpRange {
    ipv4Prefix?: string
    ipv6Prefix?: string
}

interface GoogleIpResponse {
    prefixes: IpRange[]
}

async function fetchRanges(url: string): Promise<IpRange[]> {
    const res = await fetch(url)
    if (!res.ok) {
        throw new Error(`Failed to fetch ${url}: ${res.status} ${res.statusText}`)
    }
    const data = (await res.json()) as GoogleIpResponse
    return data.prefixes ?? []
}

async function main() {
    console.log('⬇  Fetching Googlebot IP ranges...')

    const [googlebotRanges, userTriggeredRanges, specialCrawlerRanges] = await Promise.all([
        fetchRanges(GOOGLEBOT_URL),
        fetchRanges(USER_TRIGGERED_URL),
        fetchRanges(SPECIAL_CRAWLERS_URL),
    ])

    // Merge and deduplicate
    const seen = new Set<string>()
    const merged: IpRange[] = []

    for (const range of [...googlebotRanges, ...userTriggeredRanges, ...specialCrawlerRanges]) {
        const key = range.ipv4Prefix ?? range.ipv6Prefix ?? ''
        if (key && !seen.has(key)) {
            seen.add(key)
            merged.push(range)
        }
    }

    const output = {
        _comment: 'Auto-generated by scripts/fetch-googlebot-cidrs.ts — do not edit manually',
        _fetchedAt: new Date().toISOString(),
        _sources: [GOOGLEBOT_URL, USER_TRIGGERED_URL, SPECIAL_CRAWLERS_URL],
        prefixes: merged,
    }

    const outPath = join(process.cwd(), 'src', 'lib', 'googlebot-cidrs.json')
    mkdirSync(join(process.cwd(), 'src', 'lib'), { recursive: true })
    writeFileSync(outPath, JSON.stringify(output, null, 2) + '\n')

    const v4 = merged.filter((r) => r.ipv4Prefix).length
    const v6 = merged.filter((r) => r.ipv6Prefix).length
    console.log(`✅  Wrote ${merged.length} ranges (${v4} IPv4, ${v6} IPv6) → src/lib/googlebot-cidrs.json`)
}

main().catch((e) => {
    console.error('❌  Failed to fetch Googlebot CIDRs:', e)
    process.exit(1)
})
