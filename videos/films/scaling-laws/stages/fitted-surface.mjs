import { spoken } from '../cue.mjs';
import { surfaceLoss } from '../arithmetic.mjs';
import { scalingEvent } from '../construction.mjs';
import { EXPONENT_GRID } from '../model.mjs';
import { band, plot, point, rectangle, text } from '../defaults.mjs';
export function drawFittedSurface(ctx, scene, state, api) {
  const { C: themeColors } = api,
    currentBeat = state.beat ?? 0,
    progress = scalingEvent(scene, state),
    end = progress === 1;
  const X = (x, a, z, l, w) => l + ((x - a) / (z - a)) * w,
    Y = (y, a, z, t, h) => t + h - ((y - a) / (z - a)) * h;
  const result = (caption) => {
    if (end) text(ctx, api, caption, 960, 960, 36, themeColors.green, 'center');
  };
  api.focus.target('sl-fitted-surface-construction', () => {
    band(ctx, api, 'Loss values generated by a known formula');
    if (currentBeat === 1) {
      const grid = EXPONENT_GRID,
        pl = plot(ctx, api, 260, 390, 560, 400, [8, 9.1], [9, 10.4], 'log₁₀ N', 'log₁₀ D');
      for (const r of grid.rows)
        point(ctx, api, pl, Math.log10(r.n), Math.log10(r.d), themeColors.cyan, 8);
      text(
        ctx,
        api,
        'Known floor E = 1.10     A = 2.80     B = 7.80',
        960,
        320,
        30,
        themeColors.muted,
        'center',
      );
      const admitted = Math.floor(progress * grid.cells.length);
      for (const [i, g] of grid.cells.entries()) {
        const x = 1050 + g.i * 29,
          y = 380 + g.j * 16;
        const alpha = i < admitted ? 0.13 + 0.75 / (1 + g.sse * 300) : 0.03;
        rectangle(ctx, api, x, y, 24, 12, 'rgba(82,206,211,' + alpha + ')');
      }
      text(
        ctx,
        api,
        'Search grid detail   ·   α across, β down',
        1320,
        850,
        29,
        themeColors.ink,
        'center',
      );
      if (spoken(scene, state, 'fit-answer').phase === 'after') {
        const g = grid.best;
        rectangle(ctx, api, 1048 + g.i * 29, 378 + g.j * 16, 28, 16, themeColors.yellow);
        text(
          ctx,
          api,
          'α ' + g.alpha.toFixed(3) + ' · β ' + g.beta.toFixed(3),
          1320,
          915,
          35,
          themeColors.green,
          'center',
        );
        if (spoken(scene, state, 'fit-holdout').phase === 'after')
          text(
            ctx,
            api,
            'Held-out forecast ' + surfaceLoss(1e9, 1e11).toFixed(3) + '   ·   rounded value 2.408',
            960,
            985,
            31,
            themeColors.green,
            'center',
          );
      }
      return;
    }
    const data = EXPONENT_GRID.rows;
    const pl = plot(
      ctx,
      api,
      340,
      370,
      1180,
      420,
      [8, 11],
      [9, 13],
      'log₁₀ parameters N',
      'log₁₀ presentations D',
    );
    for (let i = 0; i < data.length; i++)
      if (i < Math.ceil(progress * 8) || currentBeat > 0) {
        const { n, d, loss } = data[i];
        point(ctx, api, pl, Math.log10(n), Math.log10(d), themeColors.cyan);
        text(
          ctx,
          api,
          loss.toFixed(3),
          X(Math.log10(n), 8, 11, 340, 1180) + 15,
          Y(Math.log10(d), 9, 13, 370, 420) - 15,
          25,
          themeColors.ink,
        );
      }
    point(ctx, api, pl, 9, 11, currentBeat > 0 && end ? themeColors.green : themeColors.yellow, 12);
    text(
      ctx,
      api,
      currentBeat > 0 && end ? 'Held out 2.408' : 'Held-out row',
      X(9, 8, 11, 340, 1180) + 20,
      Y(11, 9, 13, 370, 420) - 20,
      28,
      themeColors.yellow,
    );
    if (currentBeat > 0) {
      point(ctx, api, pl, Math.log10(70e9), Math.log10(1.4e12), themeColors.pink, 12);
      text(
        ctx,
        api,
        (spoken(scene, state, 'fit-target').phase === 'after'
          ? 'Forecast ' + surfaceLoss(70e9, 1.4e12).toFixed(3)
          : 'Forecast pending') + ' at 70B / 1.4T',
        1280,
        360,
        29,
        themeColors.pink,
        'center',
      );
    }
    result(
      currentBeat === 0
        ? 'Eight fitting rows · ninth 1B/100B row held out'
        : currentBeat === 1
          ? 'Grid recovers α 0.070,β 0.098 · forecast 2.091'
          : 'Check the forecast against a trained model at an intermediate size.',
    );
  });
}
export default {
  id: 'fitted-surface',
  draw: drawFittedSurface,
  cues: [
    'sl-fitted-surface-0',
    'sl-fitted-surface-1',
    'sl-fitted-surface-2',
    'fit-answer',
    'fit-holdout',
    'fit-target',
  ],
};
