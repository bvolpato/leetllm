function squaredErrorWindow(start, targets, split) {
  const gradients = targets.map((target) => 2 * (start - target));
  const groups = [gradients.slice(0, split), gradients.slice(split)];
  const counts = groups.map((group) => group.length);
  const means = groups.map((group) => group.reduce((sum, g) => sum + g, 0) / group.length);
  const weighted = means.reduce((sum, mean, i) => sum + (counts[i] / targets.length) * mean, 0);
  const wrong = (means[0] + means[1]) / means.length;
  return { start, targets, gradients, counts, means, weighted, wrong };
}

