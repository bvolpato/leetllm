export const PRESCRIBED = (() => {
  let mean = [0, 0],
    square = [0, 0],
    rms = [0, 0];
  return PRESCRIBED_GRADIENTS.map((gradient, i) => {
    const oldMean = [...mean],
      oldSquare = [...square],
      oldRms = [...rms],
      t = i + 1;
    mean = mean.map((x, j) => 0.9 * x + 0.1 * gradient[j]);
    square = square.map((x, j) => 0.999 * x + 0.001 * gradient[j] ** 2);
    rms = rms.map((x, j) => 0.9 * x + 0.1 * gradient[j] ** 2);
    const correctedMean = mean.map((x) => x / (1 - 0.9 ** t));
    const correctedSquare = square.map((x) => x / (1 - 0.999 ** t));
    return {
      t,
      gradient,
      oldMean,
      oldSquare,
      oldRms,
      mean: [...mean],
      square: [...square],
      rms: [...rms],
      rmsUpdate: gradient.map((g, j) => (0.01 * g) / (Math.sqrt(rms[j]) + 1e-8)),
      adamUpdate: correctedMean.map((m, j) => (0.01 * m) / (Math.sqrt(correctedSquare[j]) + 1e-8)),
      correctedMean,
      correctedSquare,
    };
  });
})();
